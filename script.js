// ── Purposeful motion ──
//
// system.md allows two moments that need script: the Edge Sight slider teaching
// itself, and case metrics appearing when first read. (The hero entrance and the
// robot focus are CSS-only, behind the same html.motion class.) Both run once,
// stop watching the page afterwards, and never run at all when the head gate
// left html.motion off (reduced motion) or when IntersectionObserver is missing.
function motionEnabled() {
	return (
		document.documentElement.classList.contains("motion") &&
		"IntersectionObserver" in window &&
		window.matchMedia("(prefers-reduced-motion: no-preference)").matches
	);
}

// html.motion-lite (head gate, or sampleFrameRate below) marks a slow machine:
// process explanations, the indicator crossfade and the head turn are skipped
// and every state is shown instantly.
function isLite() {
	return document.documentElement.classList.contains("motion-lite");
}

// Resolves once we know whether this machine is slow: immediately when the head
// gate already decided, otherwise after the idle frame sample below.
let settleMotionLite = () => {};
const motionLiteSettled = new Promise((resolve) => {
	settleMotionLite = resolve;
});

// Once, after load, times a small CPU loop and then ~1s of idle frame intervals. A median
// above 20ms, or 15% of frames above 25ms, means the page cannot keep 60fps
// here, so the calm version takes over. Cheap: one rAF loop, one pass.
function sampleFrameRate() {
	if (!motionEnabled() || isLite() || !("requestAnimationFrame" in window)) {
		settleMotionLite();
		return;
	}

	const begin = () => {
		if (document.hidden) {
			// rAF is paused in background tabs; intervals would be meaningless.
			settleMotionLite();
			return;
		}

		// An idle page renders cheaply even on a slow CPU, so frame times alone
		// miss it. A fixed 300k-step loop takes ~1.5ms on a modern desktop and
		// 2-3x that or more on slow hardware: best of five, over 3.5ms is slow.
		let best = Infinity;
		for (let run = 0; run < 5; run += 1) {
			const t0 = performance.now();
			let sink = 0;
			for (let i = 0; i < 300000; i += 1) {
				sink += Math.sqrt(i) * (i & 3);
			}
			best = Math.min(best, performance.now() - t0 + (sink < 0 ? 1 : 0));
		}

		if (best > 3.5) {
			document.documentElement.classList.add("motion-lite");
			settleMotionLite();
			return;
		}

		const intervals = [];
		const start = performance.now();
		let last = 0;

		const sample = (now) => {
			if (document.hidden) {
				settleMotionLite();
				return;
			}

			if (last) {
				intervals.push(now - last);
			}
			last = now;

			if (now - start < 1000) {
				window.requestAnimationFrame(sample);
				return;
			}

			const sorted = intervals.slice(1).sort((a, b) => a - b);

			if (sorted.length >= 8) {
				const median = sorted[Math.floor(sorted.length / 2)];
				const slowShare = sorted.filter((value) => value > 25).length / sorted.length;

				if (median > 20 || slowShare >= 0.15) {
					document.documentElement.classList.add("motion-lite");
				}
			}

			settleMotionLite();
		};

		window.requestAnimationFrame(sample);
	};

	// Wait for the entrance animations to finish so they do not count as load.
	const afterLoad = () => window.setTimeout(begin, 1000);

	if (document.readyState === "complete") {
		afterLoad();
	} else {
		window.addEventListener("load", afterLoad, { once: true });
	}
}

const easeInOut = (t) => (t < 0.5 ? 2 * t * t : 1 - Math.pow(-2 * t + 2, 2) / 2);

// Sweeps the range from its current value to 65, then 35, then back (1.4s).
// `apply` is the slider's own update path, so the picture and the input value
// stay in sync. Setting `.value` fires no event, so nothing is announced.
function demonstrateComparison(range, apply) {
	if (!motionEnabled()) {
		return;
	}

	const origin = Number(range.value);
	const legs = [
		{ to: 65, duration: 400 },
		{ to: 35, duration: 500 },
		{ to: origin, duration: 500 },
	];
	const cancelEvents = ["pointerdown", "keydown", "focus", "input"];
	let frame = 0;
	let started = false;
	let done = false;

	const stop = () => {
		if (done) {
			return;
		}
		done = true;
		cancelAnimationFrame(frame);
		observer.disconnect();
		cancelEvents.forEach((type) => range.removeEventListener(type, stop));
	};

	const run = () => {
		started = true;
		const begin = performance.now();
		let from = origin;
		let legStart = begin;
		let index = 0;

		const step = (now) => {
			if (done) {
				return;
			}
			const leg = legs[index];
			const progress = Math.min((now - legStart) / leg.duration, 1);
			range.value = String(from + (leg.to - from) * easeInOut(progress));
			apply();

			if (progress < 1) {
				frame = requestAnimationFrame(step);
				return;
			}
			if (index === legs.length - 1) {
				range.value = String(origin);
				apply();
				stop();
				return;
			}
			from = leg.to;
			legStart = now;
			index += 1;
			frame = requestAnimationFrame(step);
		};

		frame = requestAnimationFrame(step);
	};

	const observer = new IntersectionObserver(
		(entries) => {
			const entry = entries[entries.length - 1];
			if (!started && entry.intersectionRatio >= 0.5) {
				run();
			} else if (started && entry.intersectionRatio < 0.1) {
				// Scrolled away mid-demo: leave the slider where it started.
				range.value = String(origin);
				apply();
				stop();
			}
		},
		{ threshold: [0.1, 0.5] },
	);

	cancelEvents.forEach((type) => range.addEventListener(type, stop));
	observer.observe(range.closest("[data-comparison]") || range.closest(".comparison-card") || range);
}

