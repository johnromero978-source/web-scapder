function applyLanguage(lang, { persist = true } = {}) {
	const dictionary = translations[lang] || translations.es;
	document.documentElement.lang = lang === "pt" ? "pt-BR" : lang;
	document.title = dictionary.metaTitle;
	document
		.querySelector('meta[name="description"]')
		?.setAttribute("content", dictionary.metaDescription);

	document.querySelectorAll("[data-i18n]").forEach((node) => {
		const key = node.getAttribute("data-i18n");
		// /en/ and /pt/ ship already translated: leave identical text untouched.
		if (dictionary[key] && node.textContent !== dictionary[key]) {
			node.textContent = dictionary[key];
		}
	});

	document.querySelectorAll("[data-i18n-html]").forEach((node) => {
		const key = node.getAttribute("data-i18n-html");
		if (dictionary[key]) {
			node.innerHTML = dictionary[key];
		}
	});

	document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
		const key = node.getAttribute("data-i18n-aria-label");
		if (dictionary[key]) {
			node.setAttribute("aria-label", dictionary[key]);
		}
	});

	document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
		const key = node.getAttribute("data-i18n-alt");
		if (dictionary[key]) {
			node.setAttribute("alt", dictionary[key]);
		}
	});

	document.querySelectorAll(".language-option").forEach((button) => {
		const isActive = button.dataset.lang === lang;
		button.classList.toggle("is-active", isActive);
		button.setAttribute("aria-pressed", String(isActive));
	});

	if (persist) {
		window.localStorage.setItem("scapder-language", lang);
	}

	syncBandada(lang);
	document.dispatchEvent(new CustomEvent("scapder:language", { detail: lang }));
}

// ── Bandada embed ──
//
// The Sentientum dialog shows https://bandada.scapder.com/ in place. The iframe
// does not exist in the HTML: it is mounted when the dialog opens and removed
// when it closes, so the page loads nothing from Bandada until someone asks.
function bandadaUrl(lang) {
	return `https://bandada.scapder.com/?lang=${encodeURIComponent(lang)}`;
}

function currentLanguage() {
	const lang = document.documentElement.lang;
	return lang.startsWith("pt") ? "pt" : lang === "en" ? "en" : "es";
}

function mountBandada() {
	const frame = document.querySelector("[data-bandada-frame]");
	if (!frame || frame.querySelector("iframe")) {
		return;
	}

	const iframe = document.createElement("iframe");
	iframe.className = "modal-embed-iframe";
	iframe.src = bandadaUrl(currentLanguage());
	iframe.title = translations[currentLanguage()].bandadaFrameTitle;
	iframe.referrerPolicy = "strict-origin-when-cross-origin";
	frame.appendChild(iframe);
}

function teardownBandada() {
	const iframe = document.querySelector("[data-bandada-frame] iframe");
	if (iframe) {
		iframe.remove();
	}
}

// Keeps the full-screen link and any mounted iframe on the page language.
function syncBandada(lang) {
	const link = document.querySelector("[data-bandada-fullscreen]");
	if (link) {
		link.href = bandadaUrl(lang);
	}

	const iframe = document.querySelector("[data-bandada-frame] iframe");
	if (iframe) {
		iframe.src = bandadaUrl(lang);
		iframe.title = translations[lang].bandadaFrameTitle;
	}
}

// ── Language URLs ──
//
// / is Spanish, /en/ English, /pt/ Brazilian Portuguese. The generated /en/ and
// /pt/ pages are already translated, so the path always decides there (and is not
// written to the saved choice: opening a shared link must not change the visitor's
// preference). On / the saved choice still applies, as before.
const LANGUAGE_PATHS = { es: "/", en: "/en/", pt: "/pt/" };

const pathLanguage = (() => {
	const match = /^\/(en|pt)(?:\/|$)/.exec(window.location.pathname);
	return match ? match[1] : null;
})();

// Keeps the address in step with the chosen language without a navigation.
function syncLanguageUrl(lang) {
	if (window.location.protocol === "file:" || !window.history || !window.history.replaceState) {
		return;
	}
	const target = LANGUAGE_PATHS[lang] || "/";
	if (window.location.pathname === target) {
		return;
	}
	try {
		window.history.replaceState(window.history.state, "", target + window.location.search + window.location.hash);
	} catch {
		// Sandboxed or unusual origins may refuse; the language switch itself still works.
	}
}

if (pathLanguage) {
	applyLanguage(pathLanguage, { persist: false });
} else {
	const savedLanguage = window.localStorage.getItem("scapder-language");
	applyLanguage(savedLanguage === "en" || savedLanguage === "pt" ? savedLanguage : "es");
}

