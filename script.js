// ── Detail dialogs ──
//
// Opened from a product card. Keyboard and screen-reader behaviour is the part
// worth writing by hand: Escape closes, focus moves into the panel and returns
// to the card that opened it, and Tab is kept inside while it is open — a
// dialog you can Tab out of silently is a dialog that is not one.
document.querySelectorAll("[data-modal-open]").forEach((trigger) => {
	const modal = document.getElementById(trigger.dataset.modalOpen);
	if (!modal) {
		return;
	}

	const panel = modal.querySelector(".modal-panel");
	const focusable = () =>
		[...modal.querySelectorAll('a[href], iframe, button:not([disabled]), [tabindex]:not([tabindex="-1"])')].filter(
			(node) => node.offsetParent !== null,
		);

	const close = () => {
		modal.hidden = true;
		document.body.style.removeProperty("overflow");
		// Unmount the embed: a hidden dialog must not keep a live app running.
		teardownBandada();
		trigger.focus();
	};

	const onKeydown = (event) => {
		if (modal.hidden) {
			return;
		}

		if (event.key === "Escape") {
			close();
			return;
		}

		if (event.key !== "Tab") {
			return;
		}

		const nodes = focusable();
		if (nodes.length === 0) {
			return;
		}

		const first = nodes[0];
		const last = nodes[nodes.length - 1];

		if (event.shiftKey && document.activeElement === first) {
			event.preventDefault();
			last.focus();
		} else if (!event.shiftKey && document.activeElement === last) {
			event.preventDefault();
			first.focus();
		}
	};

	trigger.addEventListener("click", () => {
		modal.hidden = false;
		// The page behind must not scroll under the dialog.
		document.body.style.overflow = "hidden";
		if (panel) {
			panel.scrollTop = 0;
		}
		mountBandada();
		// The close button, never the iframe: focus parked inside a cross-origin
		// frame swallows keys and Escape would stop closing the dialog.
		const closeButton = modal.querySelector(".modal-close");
		if (closeButton) {
			closeButton.focus();
		}
	});

	modal.querySelectorAll("[data-modal-close]").forEach((node) => {
		node.addEventListener("click", close);
	});

	document.addEventListener("keydown", onKeydown);
});

